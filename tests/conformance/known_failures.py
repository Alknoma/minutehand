"""The ratchet: every (provider, property, case) the suite runs that fails on today's trunk, with the failure as
observed, in one line. A listed case is expected to fail, strictly: when it starts passing, the run fails until its
entry is removed, so every fix is recorded here. An unlisted failure fails the run. This table may only shrink.

Regenerated by hand from a run: never add an entry to make a red case green without the line saying what the
provider does wrong."""

from __future__ import annotations

from dataclasses import dataclass

from tests.conformance.contract import Property


@dataclass(frozen=True)
class Known:
    provider: str
    prop: Property
    case: str
    observed: str


KNOWN: tuple[Known, ...] = ()
